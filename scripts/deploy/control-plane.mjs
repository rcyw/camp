const execute = promisify(execFile);
const fail = message => Object.assign(new Error(message), { code: 'camp_control_deployment' });
const path = value => typeof value === 'string' && value !== '/' && isAbsolute(value) && /^\/[A-Za-z0-9_./-]+$/.test(value) && resolve(value) === value;
export function controlConfiguration(input) {
  if (!input || Object.keys(input).some(key => !['publicIp', 'apiPort', 'webPort', 'webRoot', 'rootCaDir', 'pkiDir', 'scriptPath', 'nodePath', 'configPath'].includes(key)) || isIP(input.publicIp) !== 4) throw fail('Use an explicit IPv4 address and known deployment fields');
  const config = { apiPort: 13018, webPort: 15190, ...input };
  for (const field of ['apiPort', 'webPort']) if (!Number.isSafeInteger(config[field]) || config[field] < 1024 || config[field] > 65535) throw fail('Upstreams must use non-privileged local ports');
  if (config.apiPort === config.webPort || !['pkiDir', 'scriptPath', 'nodePath', 'configPath'].every(key => path(config[key])) || ['webRoot', 'rootCaDir'].some(key => config[key] !== undefined && !path(config[key]))) throw fail('Use distinct upstream ports and canonical absolute deployment paths');
  if (config.rootCaDir && (config.rootCaDir.startsWith(config.pkiDir + '/') || [config.pkiDir, config.scriptPath, config.nodePath, config.configPath, config.webRoot].filter(Boolean).some(value => value === config.rootCaDir || value.startsWith(config.rootCaDir + '/')))) throw fail('The offline root cannot contain online configuration, code or issuer state');
  return config;
}
export function renderControlDeployment(input) {
  const c = controlConfiguration(input);
  const webLocation = c.webRoot ? `root ${c.webRoot};\n  location / { try_files $uri $uri/ /index.html; }` : `location / { proxy_pass http://127.0.0.1:${c.webPort}; }`;
  return {
    'camp-control.conf': `# Generated by Camp; backend listeners stay on loopback.\nmap $http_upgrade $camp_connection { default upgrade; '' close; }\nserver {\n  listen 80 default_server;\n  server_name ${c.publicIp};\n  return 308 https://${c.publicIp}$request_uri;\n}\nserver {\n  listen 443 ssl default_server;\n  server_name ${c.publicIp};\n  ssl_certificate ${c.pkiDir}/server-chain.pem;\n  ssl_certificate_key ${c.pkiDir}/server.key;\n  ssl_protocols TLSv1.2 TLSv1.3;\n  ssl_session_cache shared:CampTLS:10m;\n  ssl_session_tickets off;\n  server_tokens off;\n  # Private artifact parts are 8 MiB. Never buffer private payloads to disk.\n  client_max_body_size 10m;\n  access_log off;\n  error_log /var/log/nginx/camp-control-error.log warn;\n  add_header Strict-Transport-Security "max-age=86400" always;\n  proxy_http_version 1.1;\n  proxy_set_header Host $host;\n  proxy_set_header X-Forwarded-Proto https;\n  proxy_set_header X-Forwarded-For $remote_addr;\n  proxy_set_header Upgrade $http_upgrade;\n  proxy_set_header Connection $camp_connection;\n  proxy_request_buffering off;\n  proxy_buffering off;\n  proxy_read_timeout 300s;\n  location /api/ { proxy_pass http://127.0.0.1:${c.apiPort}; }\n  location /socket.io/ { proxy_pass http://127.0.0.1:${c.apiPort}; }\n  location = /health { proxy_pass http://127.0.0.1:${c.apiPort}; }\n  location ~ /\\. { deny all; }\n  ${webLocation}\n}\n`,
    'camp-control-certificate.service': `[Unit]\nDescription=Renew Camp private control certificate\nAfter=nginx.service\n[Service]\nType=oneshot\nUMask=0077\nExecStart=${c.nodePath} ${c.scriptPath} renew --config ${c.configPath}\n# Reload runs in nginx's own unit; this issuer cannot write its PID/log files.\nExecStartPost=/usr/bin/systemctl reload nginx.service\nNoNewPrivileges=yes\nPrivateTmp=yes\nProtectHome=yes\nProtectSystem=strict\nReadWritePaths=${c.pkiDir}\n# Custody may remove the offline root directory entirely. If present, hide it.\n${c.rootCaDir ? `InaccessiblePaths=-${c.rootCaDir}\n` : ''}`,
    'camp-control-certificate.timer': '[Unit]\nDescription=Check Camp private control certificate daily\n[Timer]\nOnCalendar=daily\nRandomizedDelaySec=1h\nPersistent=true\n[Install]\nWantedBy=timers.target\n',
  };
}
async function privateDirectory(directory) {
  let ancestor = directory;
  for (;;) {
    try { if (await realpath(ancestor) !== ancestor) throw fail('PKI directories cannot have linked ancestors'); break; }
    catch (error) { if (error.code !== 'ENOENT' || dirname(ancestor) === ancestor) throw error; ancestor = dirname(ancestor); }
  }
  await trustedAncestors(ancestor);
  await mkdir(directory, { recursive: true, mode: 0o700 });
  const stat = await lstat(directory);
  if (!stat.isDirectory() || stat.isSymbolicLink() || stat.uid !== process.getuid() || (stat.mode & 0o777) !== 0o700 || await realpath(directory) !== directory) throw fail('PKI directories must be owned private ordinary canonical directories');
}
async function trustedAncestors(directory) {
  for (;;) {
    const stat = await lstat(directory);
    const trustedTemporary = directory === '/tmp' && stat.uid === 0 && !!(stat.mode & 0o1000);
    if (!stat.isDirectory() || stat.isSymbolicLink() || ![0, process.getuid()].includes(stat.uid) || !trustedTemporary && stat.mode & 0o022) throw fail('PKI directories cannot have writable or foreign-owned ancestors');
    const parent = dirname(directory); if (parent === directory) return;
    directory = parent;
  }
}
async function openssl(args) { try { return await execute('openssl', args, { timeout: 30_000, killSignal: 'SIGKILL', maxBuffer: 1024 * 1024 }); } catch { throw fail('OpenSSL certificate operation failed'); } }
async function ordinary(path, { maximum = 16384, privateKey = false } = {}) {
  const file = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
  try {
    const stat = await file.stat();
    if (!stat.isFile() || stat.nlink !== 1 || stat.uid !== process.getuid() || stat.size > maximum || (privateKey ? (stat.mode & 0o777) !== 0o600 : stat.mode & 0o022)) throw fail('PKI inputs must be bounded owned ordinary files with private signing keys');
    const bytes = Buffer.alloc(stat.size + 1); let size = 0;
    while (size < bytes.length) { const part = await file.read(bytes, size, bytes.length - size); if (!part.bytesRead) break; size += part.bytesRead; }
    if (size !== stat.size) throw fail('PKI input changed during inspection');
    return bytes.subarray(0, size);
  } finally { await file.close(); }
}
async function syncDirectory(directory) {
  const file = await open(directory, 'r');
  try { await file.sync(); } finally { await file.close(); }
}
async function publishExclusive(path, bytes, mode = 0o600) {
  const file = await open(path, 'wx', mode);
  try { await file.writeFile(bytes); await file.sync(); } finally { await file.close(); }
  await syncDirectory(dirname(path));
}
async function generateKey(path) {
  // OpenSSL writes to an existing 0600 file. Even umask 000 cannot briefly
  // expose a newly generated signing key while its command is still running.
  await publishExclusive(path, Buffer.alloc(0));
  await openssl(['genpkey', '-algorithm', 'EC', '-pkeyopt', 'ec_paramgen_curve:P-256', '-out', path]);
}
async function withPkiLock(directory, work) {
  await privateDirectory(directory);
  const file = await open(join(directory, '.issuer.lock'), constants.O_RDWR | constants.O_CREAT | constants.O_NOFOLLOW | constants.O_NONBLOCK, 0o600);
  try {
    const stat = await file.stat();
    if (!stat.isFile() || stat.nlink !== 1 || stat.uid !== process.getuid() || (stat.mode & 0o777) !== 0o600) throw fail('PKI lock must be a private ordinary file');
    // flock applies to the shared open-file description. The parent keeps it
    // after this short child exits; closing the FD (including a crash) releases
    // the lock, without stale PID files or deleting another invocation's lock.
    await new Promise((resolveLock, reject) => {
      const child = spawn('flock', ['--exclusive', '--nonblock', '3'], { stdio: ['ignore', 'ignore', 'ignore', file.fd] });
      child.once('error', () => reject(fail('Unable to acquire the PKI kernel lock')));
      child.once('close', code => code === 0 ? resolveLock() : reject(fail('Another PKI operation is already active')));
    });
    return await work();
  } finally { await file.close(); }
}
function certificates(bytes) {
  if (bytes.some(byte => byte > 0x7f)) throw fail('Expected only ASCII PEM certificates in the trust chain');
  const text = bytes.toString('ascii'), pattern = /-----BEGIN CERTIFICATE-----\r?\n[A-Za-z0-9+/=\r\n]+-----END CERTIFICATE-----/g;
  const matches = text.match(pattern);
  if (!matches?.length || text.replace(pattern, '').trim()) throw fail('Expected only PEM certificates in the trust chain');
  try { return matches.map(value => new X509Certificate(value)); } catch { throw fail('The certificate chain is invalid'); }
}
function validNow(certificate, now) { return Date.parse(certificate.validFrom) <= now && Date.parse(certificate.validTo) > now; }
function keyMatches(certificate, bytes) {
  try { return certificate.checkPrivateKey(createPrivateKey(bytes)); } catch { return false; }
}
/** Root key is kept outside the online issuer directory. Only a public root
 * certificate is distributed to Workers. Never silently replace an issuer. */
export async function initializeControlPki(input, rootDirectory) {
  const c = controlConfiguration(input);
  if (!path(rootDirectory) || rootDirectory === c.pkiDir || rootDirectory.startsWith(c.pkiDir + '/') || c.pkiDir.startsWith(rootDirectory + '/')) throw fail('Keep offline root and online issuer in separate directory trees');
  if (c.rootCaDir && c.rootCaDir !== rootDirectory) throw fail('The initialization root must match the service isolation configuration');
  return withPkiLock(c.pkiDir, () => withPkiLock(rootDirectory, async () => {
    for (const file of [join(rootDirectory, 'root.key'), join(rootDirectory, 'root.crt'), ...['issuer.key', 'issuer.crt', 'root.crt', 'server.key', 'server-chain.pem'].map(name => join(c.pkiDir, name))]) {
      try { await lstat(file); throw fail('An existing or incomplete PKI must be inspected; initialization never replaces it'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    }
    const offline = await mkdtemp(join(rootDirectory, '.initialize-')), online = await mkdtemp(join(c.pkiDir, '.initialize-'));
    try {
      const rootKey = join(offline, 'root.key'), rootCert = join(offline, 'root.crt'), issuerKey = join(online, 'issuer.key'), issuerCsr = join(online, 'issuer.csr'), issuerCert = join(online, 'issuer.crt');
      await generateKey(rootKey);
      await publishExclusive(rootCert, Buffer.alloc(0));
      await openssl(['req', '-x509', '-new', '-key', rootKey, '-days', '3650', '-sha256', '-subj', '/CN=Camp Control Root CA', '-addext', 'basicConstraints=critical,CA:TRUE,pathlen:1', '-addext', 'keyUsage=critical,keyCertSign,cRLSign', '-out', rootCert]);
      await generateKey(issuerKey);
      await openssl(['req', '-new', '-key', issuerKey, '-subj', '/CN=Camp Control Online Issuer', '-out', issuerCsr]);
      const extensions = join(online, 'issuer.ext');
      await writeFile(extensions, 'basicConstraints=critical,CA:TRUE,pathlen:0\nkeyUsage=critical,keyCertSign,cRLSign\nsubjectKeyIdentifier=hash\nauthorityKeyIdentifier=keyid:always\n', { mode: 0o600, flag: 'wx' });
      await publishExclusive(issuerCert, Buffer.alloc(0));
      await openssl(['x509', '-req', '-in', issuerCsr, '-CA', rootCert, '-CAkey', rootKey, '-set_serial', '0x' + randomBytes(16).toString('hex'), '-days', '730', '-sha256', '-extfile', extensions, '-out', issuerCert]);
      await publishExclusive(join(rootDirectory, 'root.key'), await ordinary(rootKey, { privateKey: true }));
      await publishExclusive(join(rootDirectory, 'root.crt'), await ordinary(rootCert), 0o644);
      await publishExclusive(join(c.pkiDir, 'issuer.key'), await ordinary(issuerKey, { privateKey: true }));
      await publishExclusive(join(c.pkiDir, 'issuer.crt'), await ordinary(issuerCert), 0o644);
      await publishExclusive(join(c.pkiDir, 'root.crt'), await ordinary(rootCert), 0o644);
      return await renewControlCertificateUnlocked(c, { force: true, now: Date.now() });
    } finally { await Promise.all([rm(offline, { recursive: true, force: true }), rm(online, { recursive: true, force: true })]); }
  }));
}
export async function renewControlCertificate(input, { force = false, now = Date.now() } = {}) {
  const c = controlConfiguration(input);
  return withPkiLock(c.pkiDir, () => renewControlCertificateUnlocked(c, { force, now }));
}
async function renewControlCertificateUnlocked(c, { force, now }) {
  if (!Number.isFinite(now)) throw fail('The certificate inspection time is invalid');
  const issuerBytes = await ordinary(join(c.pkiDir, 'issuer.crt')), rootBytes = await ordinary(join(c.pkiDir, 'root.crt'));
  const issuers = certificates(issuerBytes), roots = certificates(rootBytes), issuer = issuers[0], root = roots[0];
  if (issuers.length !== 1 || roots.length !== 1 || !issuer.ca || !root.ca || !root.checkIssued(root) || !root.verify(root.publicKey)
    || !issuer.checkIssued(root) || !issuer.verify(root.publicKey) || !validNow(issuer, now) || !validNow(root, now)
    || !keyMatches(issuer, await ordinary(join(c.pkiDir, 'issuer.key'), { privateKey: true }))) throw fail('The current root, issuer or signing key is invalid');
  let currentChain, keyBytes;
  try { currentChain = certificates(await ordinary(join(c.pkiDir, 'server-chain.pem'))); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  const key = join(c.pkiDir, 'server.key');
  try { keyBytes = await ordinary(key, { privateKey: true }); } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    if (currentChain) throw fail('A serving certificate has lost its private key; operator recovery is required');
  }
  const current = currentChain?.[0];
  const healthy = current && currentChain.length === 2 && currentChain[1].fingerprint256 === issuer.fingerprint256
    && !current.ca && current.checkIP(c.publicIp) && current.checkIssued(issuer) && current.verify(issuer.publicKey)
    && current.keyUsage?.includes('1.3.6.1.5.5.7.3.1') && keyMatches(current, keyBytes) && validNow(current, now)
    && Date.parse(current.validTo) <= Math.min(Date.parse(issuer.validTo), Date.parse(root.validTo));
  // Adjacent signatures and CA booleans do not prove the full certificate
  // policy: for example a self-signed root with pathlen:0 cannot delegate to
  // our online intermediate. Verify before treating a current leaf as healthy.
  if (healthy) await openssl(['verify', '-CAfile', join(c.pkiDir, 'root.crt'), '-untrusted', join(c.pkiDir, 'issuer.crt'), '-attime', String(Math.floor(now / 1000)), '-verify_ip', c.publicIp, '-purpose', 'sslserver', join(c.pkiDir, 'server-chain.pem')]);
  if (!force && healthy && Date.parse(current.validTo) - now > 30 * 86400_000) return { renewed: false, validTo: current.validTo };
  if (Math.min(Date.parse(issuer.validTo), Date.parse(root.validTo)) - now < 91 * 86400_000) throw fail('Root or online issuer requires operator renewal before another leaf can be issued');
  const stage = await mkdtemp(join(c.pkiDir, '.renew-'));
  try {
    if (!keyBytes) { const stagedKey = join(stage, 'server.key'); await generateKey(stagedKey); keyBytes = await ordinary(stagedKey, { privateKey: true }); await publishExclusive(key, keyBytes); }
    const csr = join(stage, 'leaf.csr'), cert = join(stage, 'leaf.crt'), ext = join(stage, 'leaf.ext');
    await writeFile(ext, `basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=serverAuth\nsubjectAltName=IP:${c.publicIp}\n`, { mode: 0o600, flag: 'wx' });
    await openssl(['req', '-new', '-key', key, '-subj', `/CN=${c.publicIp}`, '-out', csr]);
    await publishExclusive(cert, Buffer.alloc(0));
    await openssl(['x509', '-req', '-in', csr, '-CA', join(c.pkiDir, 'issuer.crt'), '-CAkey', join(c.pkiDir, 'issuer.key'), '-set_serial', '0x' + randomBytes(16).toString('hex'), '-days', '90', '-sha256', '-extfile', ext, '-out', cert]);
    await openssl(['verify', '-CAfile', join(c.pkiDir, 'root.crt'), '-untrusted', join(c.pkiDir, 'issuer.crt'), '-verify_ip', c.publicIp, '-purpose', 'sslserver', cert]);
    const leafBytes = await ordinary(cert), leaf = certificates(leafBytes)[0];
    if (!keyMatches(leaf, keyBytes)) throw fail('The staged leaf and serving private key differ');
    const staged = join(stage, 'chain.pem');
    await publishExclusive(staged, Buffer.concat([leafBytes, issuerBytes]), 0o644);
    await rename(staged, join(c.pkiDir, 'server-chain.pem')); await syncDirectory(c.pkiDir);
    return { renewed: true, publicIp: c.publicIp, fingerprint256: root.fingerprint256, validTo: leaf.validTo };
  } finally { await rm(stage, { recursive: true, force: true }); }
}
export function parseControlArguments(argv) {
  const [action, flag, configFile, rootFlag, rootDirectory] = argv;
  if (!['render', 'renew', 'init'].includes(action) || flag !== '--config' || !path(configFile)
    || (action === 'init' ? rootFlag !== '--root-ca-dir' || !path(rootDirectory) || argv.length !== 5 : argv.length !== 3)) throw fail('Use render|renew --config FILE, or init --config FILE --root-ca-dir PRIVATE_DIRECTORY');
  return { action, configFile, rootDirectory };
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const { action, configFile, rootDirectory } = parseControlArguments(process.argv.slice(2));
    const config = JSON.parse(await ordinary(configFile, { maximum: 64 * 1024 }));
    console.log(JSON.stringify(action === 'render' ? renderControlDeployment(config) : action === 'init' ? await initializeControlPki(config, rootDirectory) : action === 'renew' ? await renewControlCertificate(config) : (() => { throw fail('Unknown command'); })()));
  } catch (error) { console.error(JSON.stringify({ event: 'control_deployment_failed', code: error.code ?? 'camp_control_deployment' })); process.exitCode = 1; }
}
